#!/usr/bin/env python
"""Review sheet of the question pool for the user: docs/figs/text_pool/review.html (self-contained).

    ../.venv/bin/python scripts/review_question_pool.py [--pool configs/text/question_pool.json] [--out docs/figs/text_pool/review.html]

Top: the extra meaning rules (C1) for approval, next to the user's approved T-B rules. Then one section per question:
the pool sorted by distance d (text, d, sources, NLI, CoLA, the base paraphrase of grown entries) and the rejected
candidates, collapsible per reason (at most --max-rejected-per-reason shown; configs/text/question_pool_rejected.json.gz
has all).
"""
import argparse, html, json
from pathlib import Path

APPROVED = ["ends with '?'", "every protected word kept", "dictionary words only", "a/an agreement",
            "no presupposed object ('the/this <object>')", "no category or identity question about the object",
            "no whole-image reading ('image of a ...')", "no second medium word (picture, photo, ...)",
            "NLI mutual entailment >= 0.8 (both directions)", "CoLA >= max(min(0.5, a0), 0.9 a0)"]
CSS = """body{font:14px/1.45 system-ui,sans-serif;color:#1a1a1a;max-width:1100px;margin:24px auto;padding:0 16px}
h1{font-size:22px}h2{font-size:17px;margin-top:36px;border-bottom:1px solid #bbb;padding-bottom:4px}
table{border-collapse:collapse;width:100%;margin:8px 0}td,th{border-bottom:1px solid #e3e3e3;padding:3px 6px;text-align:left;vertical-align:top}
th{background:#f2f2f2;position:sticky;top:0}td.n{text-align:right;font-variant-numeric:tabular-nums;color:#444;white-space:nowrap}
.src{color:#555;font-size:12px}.base{color:#777;font-size:12px}details{margin:4px 0}summary{cursor:pointer}
.meta{color:#444}.rule li{margin:2px 0}code{background:#f2f2f2;padding:0 3px}"""


def esc(x):
    return html.escape(str(x))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pool", default="configs/text/question_pool.json")
    ap.add_argument("--out", default="docs/figs/text_pool/review.html")
    ap.add_argument("--max-rejected-per-reason", type=int, default=150)
    a = ap.parse_args()
    P = json.loads(Path(a.pool).read_text()); meta, Q = P["meta"], P["questions"]
    import gzip
    rp = Path(a.pool).with_name(Path(a.pool).stem + "_rejected.json.gz")
    rej = json.loads(gzip.decompress(rp.read_bytes())) if rp.exists() else {}
    for q, e in Q.items():
        e.setdefault("rejected", rej.get(q, []))
    h = [f"<!doctype html><meta charset=utf-8><title>Question pool review</title><style>{CSS}</style>",
         "<h1>Question pool: review sheet</h1>",
         f"<p class=meta>Pool for the continuous text block (genes t, u). Distance d = {esc(meta['distance'])} to the "
         f"original question. d_max = {meta['d_max']} ({meta['d_max_quantile']:.0%} quantile of all pool distances), "
         f"{meta['n_bands']} bands of width {meta['d_max'] / meta['n_bands']:.4f}. Generated by "
         "<code>scripts/build_question_pool.py</code>; full data in <code>configs/text/question_pool.json</code>.</p>",
         "<h2>Rules</h2><p>Already approved (T-B review and the validity filters):</p><ul class=rule>"]
    h += [f"<li>{esc(r)}</li>" for r in APPROVED]
    h += ["</ul><p><b>Extra meaning rules, proposed by C1, for approval</b> (each rejects candidates that passed NLI "
          "but change what is asked):</p><ol class=rule>"]
    h += [f"<li>{esc(r)}</li>" for r in meta.get("extra_rules", [])]
    h += ["<li>growth only: a grown entry (word substitutions on a paraphrase, extra T5 samples) may use only words "
          "that occur in an original question or in an accepted first-pass entry of any question</li></ol>",
          "<h2>Overview</h2><table><tr><th>question</th><th>pool</th><th>ceiling d</th><th>below d_max?</th>"
          "<th>substitution</th><th>bank</th><th>t5</th><th>paraphrase+substitution</th><th>rejected</th></tr>"]
    for q, e in Q.items():
        s = e["n_by_source"]
        h.append(f"<tr><td><a href='#q{list(Q).index(q)}'>{esc(q)}</a></td><td class=n>{e['n_pool']}</td>"
                 f"<td class=n>{e.get('ceiling', 0):.3f}</td><td>{'yes' if e.get('ceiling', 0) < meta['d_max'] else ''}</td>"
                 + "".join(f"<td class=n>{s.get(k, 0)}</td>" for k in ("substitution", "bank", "t5", "paraphrase+substitution"))
                 + f"<td class=n>{len(e['rejected'])}</td></tr>")
    h.append("</table><p class=meta>Sources overlap (an entry found by two routes counts in both).</p>")
    for i, (q, e) in enumerate(Q.items()):
        h += [f"<h2 id=q{i}>{esc(q)}</h2>",
              f"<p class=meta>protected: {esc(', '.join(e['protect']))}; pool {e['n_pool']} of {e['n_candidates']} "
              f"candidates; CoLA original {e['cola_original']} (threshold {e['cola_threshold']})</p>",
              "<details open><summary>pool, sorted by d</summary><table><tr><th>#</th><th>d</th><th>question</th>"
              "<th>sources</th><th>NLI</th><th>CoLA</th></tr>"]
        for k, x in enumerate(e["pool"], 1):
            base = ""
            if x.get("edits") and isinstance(x["edits"][0], str):
                base = f"<div class=base>from: {esc(x['edits'][0])}</div>"
            h.append(f"<tr><td class=n>{k}</td><td class=n>{x['dist']:.3f}</td><td>{esc(x['text'])}{base}</td>"
                     f"<td class=src>{esc(', '.join(x['sources']))}</td><td class=n>{x['nli']:.2f}</td>"
                     f"<td class=n>{x['cola']:.2f}</td></tr>")
        h.append("</table></details>")
        by = {}
        for r in e["rejected"]:
            rr = r["reason"]
            key = rr.split(" 0.")[0].split(" 1.")[0] if rr.startswith(("NLI", "CoLA")) else rr.split(":")[0] if rr.startswith(("growth", "'image", "'can you")) else rr
            by.setdefault(key, []).append(r)
        h.append(f"<details><summary>rejected: {len(e['rejected'])} candidates, {len(by)} reasons</summary>")
        for key, rs in sorted(by.items(), key=lambda kv: -len(kv[1])):
            h.append(f"<details style='margin-left:16px'><summary>{esc(key)} ({len(rs)})</summary><table>"
                     "<tr><th>candidate</th><th>source</th><th>reason</th></tr>")
            h += [f"<tr><td>{esc(r['text'])}</td><td class=src>{esc(', '.join(r['sources']))}</td><td class=src>{esc(r['reason'])}</td></tr>"
                  for r in rs[:a.max_rejected_per_reason]]
            if len(rs) > a.max_rejected_per_reason:
                h.append(f"<tr><td colspan=3 class=meta>... {len(rs) - a.max_rejected_per_reason} more in the JSON</td></tr>")
            h.append("</table></details>")
        h.append("</details>")
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("\n".join(h) + "\n")
    print(a.out)


if __name__ == "__main__":
    main()
