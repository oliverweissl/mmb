#!/usr/bin/env python
"""T-B paraphrase bank (2026-11-28): whole-question paraphrases for the text channel, precomputed per prompt so the
exact list that a run can use is reviewable by hand (docs/PARAPHRASES_T-B.md) and versioned
(configs/text/paraphrase_bank.json).

Per distinct prompt of the cell files (held-out calibration sets and the study cells):
1. generate: T5-base paraphraser (humarin/chatgpt_paraphraser_on_T5_base), beam search + seeded samples (top-p 0.95,
   seed 0); de-duplicated;
   (plain beam search, 32 beams, + 256 seeded samples; group beam search needs remote code and is not used)
2. filter (first failing reason recorded): ends with "?"; every protected word kept (whole word / phrase);
   dictionary words only (wamerican, lowercase entries) apart from protected words; meaning rules (user review
   2026-11-28): no presupposed object ("the/this <obj>"), no identity/category question, no whole-image reading
   ("image of a ..."), no second medium word ("picture", "photo"); NLI mutual entailment
   >= 0.8 (cross-encoder/nli-deberta-v3-base, both directions); CoLA acceptability >= max(min(0.5, a0), 0.9 a0);
3. rank by MiniLM sentence distance to the original (the T-A text-strength unit), nearest first.

    python scripts/build_paraphrase_bank.py --out configs/text/paraphrase_bank.json --doc docs/PARAPHRASES_T-B.md
"""
import argparse, glob, json, re
from pathlib import Path

import torch
import yaml

from mmb.manipulator.text.operators import semantic as S

GEN = "humarin/chatgpt_paraphraser_on_T5_base"
# meaning rules (user review, 2026-11-28), checked after the protected-word and dictionary filters
GENERIC_PROTECTED = {"image", "subject"}


def meaning_rule(text: str, prot: list[str]) -> str | None:
    """Reason string if a paraphrase changes what is asked, else None."""
    low = text.lower()
    objs = [p for p in prot if p not in GENERIC_PROTECTED]
    for o in objs:          # POPE: the object must not be presupposed (adversarial no-items)
        if re.search(r"\b(the|this|that|these|those)\s+" + re.escape(o.split()[0]) + r"\b", low):
            return "presupposes the object (definite article / demonstrative before it)"
        if re.search(re.escape(o) + r"\b[^?]*\b(a|an)\s+(human|man|woman|animal|thing|object|kind|real)\b", low):
            return "category or identity question about the object"
    if re.search(r"\bimage of (a|an|any|the)\b", low):
        return "whole-image reading ('image of a ...')"
    if re.search(r"\b(picture|photograph|photo|snapshot)\b", low):
        return "garbled: second medium word next to 'image'"
    if re.search(r"\b(present|captured)\s*\?$", low) and "image of" in low:
        return "garbled"
    return None


CELL_GLOBS = ("cells/*_calib.yaml", "cells/*_calib2.yaml", "cells/*_cells.yaml")


def prompts() -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for f in sorted({p for g in CELL_GLOBS for p in glob.glob(g)}):
        for it in yaml.safe_load(open(f))["seeds"]["slot_items"]["items"]:
            out.setdefault(it["prompt"], sorted({str(w).lower() for w in (it.get("meta") or {}).get("protect_words") or []}))
    return out


def generate(tok, mod, q: str) -> list[str]:
    enc = tok(f"paraphrase: {q}", return_tensors="pt", truncation=True, max_length=128)
    with torch.no_grad():
        beams = mod.generate(**enc, num_beams=32, num_return_sequences=32, repetition_penalty=1.5, max_length=64)
        torch.manual_seed(0)
        samp = mod.generate(**enc, do_sample=True, top_p=0.95, temperature=1.0, num_return_sequences=256, max_length=64)
    seen, out = set(), []
    for s in tok.batch_decode(beams, skip_special_tokens=True) + tok.batch_decode(samp, skip_special_tokens=True):
        s = re.sub(r"\s+", " ", s).strip()
        k = s.lower().rstrip("?").strip()
        if s and k != q.lower().rstrip("?").strip() and k not in seen:
            seen.add(k); out.append(s)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(); ap.add_argument("--out", type=Path, required=True); ap.add_argument("--doc", type=Path, required=True)
    a = ap.parse_args()
    from transformers import AutoModelForSeq2SeqLM, AutoTokenizer
    tok = AutoTokenizer.from_pretrained(GEN); mod = AutoModelForSeq2SeqLM.from_pretrained(GEN).eval()
    op = S.SemanticSubstitutionOperator(device="cpu"); op._ensure_semantic_loaded()
    words = S._wordlist() or frozenset()
    bank, md = {}, ["# T-B paraphrase bank (review list)", "",
                    "Generated by scripts/build_paraphrase_bank.py. Accepted paraphrases per prompt, nearest first "
                    "(MiniLM distance d = 1 - cos; NLI = mutual entailment; CoLA = acceptability, original in the header). "
                    "A run's paraphrase gene picks rank 1, 2, 4, 8, ... of this list. Rejected candidates are counted by reason; those "
                    "rejected by the meaning rules (user review 2026-11-28: presupposed object, identity question, whole-image "
                    "reading, second medium word), NLI or CoLA are listed under each prompt.", ""]
    for q, prot in prompts().items():
        cands = generate(tok, mod, q)
        a0 = float(op.acceptability([q])[0]); thr = max(min(0.5, a0), 0.9 * a0)
        rej, keep, rej_items = {}, [], []
        def bad(r): rej[r] = rej.get(r, 0) + 1
        pre = []
        for c in cands:
            low = c.lower()
            if not c.endswith("?"):
                bad("not a question"); continue
            if not all(re.search(r"\b" + re.escape(p) + r"\b", low) for p in prot):
                bad("protected word lost"); continue
            toks = re.findall(r"[A-Za-z]+", c)
            if any(t.lower() not in words and t.lower() not in prot and t not in words for t in toks):
                bad("non-dictionary word"); continue
            why = meaning_rule(c, prot)
            if why:
                bad(why); rej_items.append((c, why)); continue
            pre.append(c)
        ent = op.mutual_entailment(q, pre) if pre else []
        acc = op.acceptability(pre) if pre else []
        ok = [i for i in range(len(pre)) if ent[i] >= 0.8 and acc[i] >= thr]
        for i in range(len(pre)):
            if ent[i] < 0.8:
                bad("NLI < 0.8"); rej_items.append((pre[i], f"NLI mutual entailment {float(ent[i]):.2f} < 0.8"))
            elif acc[i] < thr:
                bad("CoLA below threshold"); rej_items.append((pre[i], f"CoLA {float(acc[i]):.2f} < {thr:.2f}"))
        d = op._distances(q, [pre[i] for i in ok]) if ok else []
        ranked = sorted(((pre[i], float(d[j]), float(ent[i]), float(acc[i])) for j, i in enumerate(ok)), key=lambda x: (round(x[1], 6), x[0]))
        bank[q] = dict(protect=prot, generated=len(cands), rejected=rej,
                       paraphrases=[dict(text=t, dist=round(x, 4), nli=round(e, 3), cola=round(c_, 3)) for t, x, e, c_ in ranked])
        md += [f"## {q}", "", f"protected: {', '.join(prot) or '-'}; generated {len(cands)}, accepted {len(ranked)}; "
               f"rejected: {', '.join(f'{k} {v}' for k, v in sorted(rej.items())) or 'none'}; CoLA original {a0:.2f} (threshold {thr:.2f})", "",
               "| rank | paraphrase | d | NLI | CoLA |", "|---|---|---|---|---|"]
        md += [f"| {k + 1} | {t} | {x:.3f} | {e:.2f} | {c_:.2f} |" for k, (t, x, e, c_) in enumerate(ranked)] + [""]
        if rej_items:
            md += ["Rejected after the protected-word and dictionary filters (meaning rules, NLI, CoLA):", "",
                   "| paraphrase | reason |", "|---|---|"] + [f"| {t} | {w} |" for t, w in rej_items] + [""]
        print(f"{q}: generated {len(cands)}, accepted {len(ranked)}, rejected {rej}")
    a.out.parent.mkdir(parents=True, exist_ok=True); a.out.write_text(json.dumps(bank, indent=1, ensure_ascii=False))
    a.doc.parent.mkdir(parents=True, exist_ok=True); a.doc.write_text("\n".join(md) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
